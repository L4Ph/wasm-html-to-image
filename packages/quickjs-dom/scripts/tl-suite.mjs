// @testing-library/dom's own test suite, run twice: once under its own jsdom environment (the
// baseline) and once with the environment swapped for this package's jest environment. The
// library's tests are not in its npm package, so the matching tag of the repository is cloned
// into node_modules/.cache (a one-time download) and installed there.
//
//   node scripts/tl-suite.mjs [--keep]
//
// The result is a measurement, not an assertion: it prints both totals and the tests that fail
// only under this package, which is the list to classify in tests/known-gaps.json.
import { execFileSync, spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");
const require = createRequire(path.join(root, "package.json"));
const version = require("@testing-library/dom/package.json").version;
const dir = path.join(root, "node_modules", ".cache", "tl-dom-suite");
const run = (cmd, args, cwd) => {
  const r = spawnSync(cmd, args, { cwd, stdio: "inherit" });
  if (r.status !== 0 && cmd !== "npx") throw new Error(`${cmd} ${args.join(" ")} failed`);
  return r.status;
};

if (!existsSync(path.join(dir, "package.json"))) {
  console.log(`cloning dom-testing-library v${version} into ${dir}`);
  execFileSync("git", ["clone", "--depth", "1", "--branch", `v${version}`, "https://github.com/testing-library/dom-testing-library.git", dir], { stdio: "inherit" });
}
if (!existsSync(path.join(dir, "node_modules"))) {
  console.log("installing the suite's own dependencies");
  execFileSync("npm", ["install", "--no-audit", "--no-fund", "--loglevel=error"], { cwd: dir, stdio: "inherit" });
}
writeFileSync(
  path.join(dir, "tests", "jest.config.ours.js"),
  `// generated by scripts/tl-suite.mjs: the library's dom project with the environment swapped\nconst base = require('./jest.config.dom')\nmodule.exports = { ...base, displayName: 'ours', testEnvironment: ${JSON.stringify(path.join(root, "jest.cjs"))} }\n`,
);

const out = (name) => path.join(dir, `${name}.json`);
run("npx", ["jest", "--config", "tests/jest.config.dom.js", "--ci", "--json", "--outputFile", out("baseline")], dir);
run("npx", ["jest", "--config", "tests/jest.config.ours.js", "--ci", "--json", "--outputFile", out("ours")], dir);

const read = (name) => JSON.parse(readFileSync(out(name), "utf8"));
const failing = (d) => {
  const set = new Set();
  for (const suite of d.testResults) for (const a of suite.assertionResults) if (a.status === "failed") set.add(`${path.basename(suite.name)} :: ${a.title}`);
  return set;
};
const base = read("baseline"), ours = read("ours");
console.log(`\nbaseline (jsdom): ${base.numPassedTests}/${base.numTotalTests}`);
console.log(`ours:             ${ours.numPassedTests}/${ours.numTotalTests}`);
const onlyOurs = [...failing(ours)].filter((t) => !failing(base).has(t));
console.log(onlyOurs.length ? `\nfailing only under ours (${onlyOurs.length}):` : "\nnothing fails only under ours");
for (const t of onlyOurs) console.log(`  - ${t}`);
